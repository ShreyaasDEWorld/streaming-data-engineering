CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255),
    full_name VARCHAR(150) NOT NULL,
    country_code CHAR(2),
    acquisition_channel VARCHAR(50),
    registered_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE profiles (
    profile_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    profile_name VARCHAR(100) NOT NULL,
    birth_year INT,
    is_kids_profile BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (birth_year IS NULL OR birth_year BETWEEN 1900 AND 2100)
);

CREATE TABLE subscription_plans (
    plan_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_name VARCHAR(50) NOT NULL UNIQUE,
    monthly_price NUMERIC(10,2) NOT NULL CHECK (monthly_price >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    video_quality VARCHAR(20),
    max_screens INT NOT NULL CHECK (max_screens > 0),
    has_ads BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE subscriptions (
    subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    plan_id INT NOT NULL REFERENCES subscription_plans(plan_id),
    started_at TIMESTAMPTZ NOT NULL,
    trial_ends_at TIMESTAMPTZ,
    current_period_start TIMESTAMPTZ,
    current_period_end TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (trial_ends_at IS NULL OR trial_ends_at >= started_at),
    CHECK (current_period_end IS NULL OR current_period_start IS NULL
           OR current_period_end >= current_period_start)
);

CREATE TABLE subscription_status_history (
    status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(subscription_id),
    status VARCHAR(20) NOT NULL
        CHECK (status IN ('Trial', 'Active', 'Paused', 'Cancelled', 'Expired')),
    status_date TIMESTAMPTZ NOT NULL,
    source_event_id VARCHAR(100),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content (
    content_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    content_type VARCHAR(20) NOT NULL
        CHECK (content_type IN ('Movie', 'Series', 'Season', 'Episode')),
    parent_content_id BIGINT REFERENCES content(content_id),
    release_date DATE,
    duration_minutes INT,
    age_rating VARCHAR(20),
    original_language VARCHAR(50),
    country_of_origin VARCHAR(100),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (duration_minutes IS NULL OR duration_minutes > 0)
);

CREATE TABLE genres (
    genre_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE content_genres (
    content_id BIGINT NOT NULL REFERENCES content(content_id),
    genre_id INT NOT NULL REFERENCES genres(genre_id),
    PRIMARY KEY (content_id, genre_id)
);

CREATE TABLE devices (
    device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES profiles(profile_id),
    device_type VARCHAR(50) NOT NULL,
    device_os VARCHAR(50),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE viewing_events (
    viewing_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_event_id VARCHAR(100),
    profile_id BIGINT NOT NULL REFERENCES profiles(profile_id),
    content_id BIGINT NOT NULL REFERENCES content(content_id),
    device_id BIGINT REFERENCES devices(device_id),
    event_type VARCHAR(20) NOT NULL
        CHECK (event_type IN ('Play', 'Pause', 'Resume', 'Stop', 'Complete', 'Error')),
    event_timestamp TIMESTAMPTZ NOT NULL,
    watch_duration_seconds INT NOT NULL DEFAULT 0
        CHECK (watch_duration_seconds >= 0),
    ingestion_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT NOT NULL REFERENCES subscriptions(subscription_id),
    payment_reference VARCHAR(100),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    payment_status VARCHAR(20) NOT NULL
        CHECK (payment_status IN ('Pending', 'Succeeded', 'Failed', 'Refunded')),
    payment_method VARCHAR(50),
    transaction_at TIMESTAMPTZ NOT NULL,
    ingestion_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ad_impressions (
    impression_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id BIGINT NOT NULL REFERENCES profiles(profile_id),
    content_id BIGINT REFERENCES content(content_id),
    campaign_id VARCHAR(100) NOT NULL,
    impression_timestamp TIMESTAMPTZ NOT NULL,
    clicked BOOLEAN NOT NULL DEFAULT FALSE,
    revenue NUMERIC(10,4) NOT NULL DEFAULT 0 CHECK (revenue >= 0)
);

CREATE TABLE support_tickets (
    ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    subscription_id BIGINT REFERENCES subscriptions(subscription_id),
    issue_category VARCHAR(50) NOT NULL,
    ticket_status VARCHAR(20) NOT NULL
        CHECK (ticket_status IN ('Open', 'In Progress', 'Resolved', 'Closed')),
    priority VARCHAR(20) NOT NULL DEFAULT 'Medium',
    created_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    CHECK (resolved_at IS NULL OR resolved_at >= created_at)
);

-- Indexes for common joins and time-based queries
CREATE INDEX idx_profiles_customer
    ON profiles(customer_id);

CREATE INDEX idx_subscriptions_customer
    ON subscriptions(customer_id);

CREATE INDEX idx_status_history_subscription_date
    ON subscription_status_history(subscription_id, status_date);

CREATE INDEX idx_viewing_profile_timestamp
    ON viewing_events(profile_id, event_timestamp);

CREATE INDEX idx_viewing_content
    ON viewing_events(content_id);

CREATE INDEX idx_payments_subscription_timestamp
    ON payments(subscription_id, transaction_at);

CREATE INDEX idx_support_customer
    ON support_tickets(customer_id);

